"""
검색 Query 정의. 품질 튜닝은 이 파일만 고쳐서 반복한다.

두 갈래로 나눈 이유는 알고 싶은 것이 둘이기 때문이다.

    product   회사가 무엇을 만들었나   - 제품·서비스·기술 자체
    business  그게 실제로 팔리고 있나   - 도입·공급·계약 같은 사업화 신호

한 Query 로는 둘이 섞여 한쪽이 밀린다. 나눠서 병렬로 던지고 코드가 합친다.

---------------------------------------------------------------------------
Query 를 이 모양으로 정한 근거 (트래블월렛·이롬넷·아이씨비·센트비 4개사 실측,
topic=news / time_range=year / max_results=10. 숫자는 제목·스니펫에 회사명이 실제로
등장한 비율)

  **키워드를 길게 나열하면 회사명이 밀려난다.** 이게 가장 큰 실패 요인이었다.

    "{회사} 최신 제품 신제품 상품 서비스 출시 개발 기술"   트래블월렛  0/10  (  0%)
    "{회사} 제품 상품 서비스 판매 공급 수주 계약 고객 도입" 트래블월렛  1/16  (  6%)

  회사명은 희귀 토큰이라 검색을 지탱하는 유일한 축인데, 흔한 일반명사를 여럿 붙이면
  그 명사구가 질의를 차지해 버린다. 위 두 Query 는 삼성 갤럭시·버거킹 기사를 데려왔다.
  따옴표로 회사명을 묶어도("{회사}" + 긴 키워드) 0% 로 똑같았다. 회사명을 두 번 반복하면
  정확도는 오르지만 건수가 1~3건으로 붕괴해 못 쓴다.

  **키워드 2개까지가 한계고, 3개부터 무너진다.**

    variant                    트래블월렛  이롬넷  아이씨비  센트비   평균
    {회사} 서비스 기술            100%   100%    90%    80%   92.5%  <- product 채택
    {회사} 도입                  100%   100%   100%    50%   87.5%  <- business 채택
    {회사} 서비스 도입 고객         89%   100%     0%    30%   55%
    {회사} 도입 고객                0%   100%   100%     0%   50%
    {회사} 제품 서비스 출시         50%    20%     0%    50%   30%

  business 쪽은 "도입" 하나가 남았다. 수주·협약·공급·계약·고객사도 재 봤지만 기업마다
  복불복이었다 - 계약은 센트비 100% / 아이씨비 0%, 서비스공급은 센트비 80% / 아이씨비 0%.
  "도입" 만이 4개사에서 고르게 버텼고, 실제로 데려온 것도 사업화 기사였다
  (예: "이롬넷, 광장시장에 페이버스 QR 결제 서비스 도입").

  Query 를 바꾸려면 이 표를 다시 뽑아 비교하고 숫자를 갱신한다. 감으로 고치지 않는다.
---------------------------------------------------------------------------
"""
# (카테고리, Query 템플릿). {company} 자리에 기업명이 들어간다.
QUERY_TEMPLATES: tuple[tuple[str, str], ...] = (
    ("product", "{company} 서비스 기술"),
    ("business", "{company} 도입"),
)

CATEGORIES = tuple(category for category, _ in QUERY_TEMPLATES)


def build_queries(company: str) -> list[tuple[str, str]]:
    """기업명을 템플릿에 넣어 (카테고리, Query) 목록을 만든다."""
    name = company.strip()
    if not name:
        raise ValueError("기업명이 비어 있습니다.")

    return [(category, template.format(company=name)) for category, template in QUERY_TEMPLATES]
